export function messageFor(error: unknown, fallback: MessageKey): string {
  if (error instanceof HttpError && error.code && Object.hasOwn(errorKeys, error.code)) {
    return t(errorKeys[error.code] ?? fallback)
  }
  return t(fallback)
}
